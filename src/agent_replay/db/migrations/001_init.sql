-- Initial schema. schema_migrations is created by the runner before this file.

CREATE TABLE suite_runs (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    label         text NOT NULL DEFAULT '',
    variant       text NOT NULL DEFAULT '',
    mode          text NOT NULL DEFAULT 'record' CHECK (mode IN ('record', 'replay')),
    status        text NOT NULL DEFAULT 'running'
                  CHECK (status IN ('running', 'complete', 'stopped')),
    tasks_path    text,
    tasks_sha256  text,
    task_count    integer NOT NULL DEFAULT 0,
    source_suite_run_id uuid REFERENCES suite_runs (id),
    faults        jsonb NOT NULL DEFAULT '[]'::jsonb,
    metrics       jsonb,
    created_at    timestamptz NOT NULL DEFAULT now(),
    finished_at   timestamptz
);

CREATE TABLE runs (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    suite_run_id   uuid REFERENCES suite_runs (id) ON DELETE CASCADE,
    source_run_id  uuid REFERENCES runs (id),
    task_id        text NOT NULL DEFAULT '',
    variant        text NOT NULL DEFAULT '',
    mode           text NOT NULL CHECK (mode IN ('record', 'replay')),
    status         text NOT NULL CHECK (status IN ('ok', 'error', 'diverged', 'skipped')),
    error_type     text,
    error          text,
    final_output   text,
    faults         jsonb NOT NULL DEFAULT '[]'::jsonb,
    input_tokens   integer NOT NULL DEFAULT 0,
    output_tokens  integer NOT NULL DEFAULT 0,
    latency_ms     integer NOT NULL DEFAULT 0,
    model_calls    integer NOT NULL DEFAULT 0,
    tool_calls     integer NOT NULL DEFAULT 0,
    cache_hits     integer NOT NULL DEFAULT 0,
    cache_misses   integer NOT NULL DEFAULT 0,
    cost_usd       double precision NOT NULL DEFAULT 0,
    started_at     timestamptz NOT NULL DEFAULT now(),
    finished_at    timestamptz
);
CREATE INDEX runs_suite_run_id_idx ON runs (suite_run_id);

CREATE TABLE spans (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         uuid NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    seq            integer NOT NULL,
    trace_id       text NOT NULL DEFAULT '',
    span_id        text NOT NULL DEFAULT '',
    parent_span_id text,
    kind           text NOT NULL DEFAULT '',
    name           text NOT NULL DEFAULT '',
    status         text NOT NULL DEFAULT 'ok',
    error_type     text,
    -- GenAI semantic-convention attributes.
    attributes     jsonb NOT NULL DEFAULT '{}'::jsonb,
    -- Neutral request/response (incl. ToolCall.signature), request hash, cache status.
    payload        jsonb NOT NULL DEFAULT '{}'::jsonb,
    input_tokens   integer NOT NULL DEFAULT 0,
    output_tokens  integer NOT NULL DEFAULT 0,
    latency_ms     integer NOT NULL DEFAULT 0,
    cost_usd       double precision NOT NULL DEFAULT 0,
    cache_status   text CHECK (cache_status IN ('hit', 'miss', 'live')),
    started_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (run_id, seq)
);

CREATE TABLE scores (
    run_id      uuid NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    check_name  text NOT NULL,
    kind        text NOT NULL DEFAULT 'deterministic',
    passed      boolean,  -- NULL: judge error/skipped/budget/quota
    detail      jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (run_id, check_name)
);

CREATE TABLE model_cache (
    request_hash  text PRIMARY KEY,
    provider      text NOT NULL DEFAULT '',
    model         text NOT NULL DEFAULT '',
    request       jsonb NOT NULL DEFAULT '{}'::jsonb,
    response      jsonb NOT NULL DEFAULT '{}'::jsonb,
    input_tokens  integer NOT NULL DEFAULT 0,
    output_tokens integer NOT NULL DEFAULT 0,
    latency_ms    integer NOT NULL DEFAULT 0,
    cost_usd      double precision NOT NULL DEFAULT 0,
    created_at    timestamptz NOT NULL DEFAULT now()
);
